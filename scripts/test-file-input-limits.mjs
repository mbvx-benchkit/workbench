import assert from 'node:assert/strict';
import { readJsonFile } from '../gosplan13/dist/import-utils.js';
import { parseInventoryCsv } from '../inventory_batch/dist/csv/import.js';
const over = 10 * 1024 * 1024 + 1;
const gosOver = 64 * 1024 * 1024 + 1;
let reads = 0;
await assert.rejects(readJsonFile({size: gosOver, text: async () => {reads++; return '{}';}}), /64MiB/);
await assert.rejects(parseInventoryCsv({size: over, arrayBuffer: async () => {reads++; return new ArrayBuffer(0);}}), /10MiB/);
assert.equal(reads, 0, 'too-large input must be rejected before reading');
console.log('PASS: oversized JSON/CSV rejected before allocating file contents');
