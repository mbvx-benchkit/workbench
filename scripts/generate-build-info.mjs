/** Generate the shared footer metadata and the GitHub changelog from one source. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const records=JSON.parse(fs.readFileSync(path.join(root,'release-notes.json'),'utf8'));
const categories={features:'新機能',ux:'UI・UXの改善',fixes:'不具合修正',security:'セキュリティ・信頼性の向上',internal:'性能・内部処理の改善'};
const repository='https://github.com/mbvx-benchkit/workbench/';
const semver=/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const plain=s=>typeof s==='string' && s.trim()===s && s.length>0 && !/[\x00-\x1f\x7f]/.test(s);
const validDate=s=>typeof s==='string' && /^\d{4}-\d{2}-\d{2}$/.test(s) && !Number.isNaN(Date.parse(s)) && new Date(s).toISOString().slice(0,10)===s;
const parts=s=>s.split('.').map(Number);
const newer=(a,b)=>{const x=parts(a),y=parts(b);for(let i=0;i<3;i++){if(x[i]!==y[i])return x[i]>y[i];}return false;};
const validTarget=/^(?:commit\/[a-f0-9]{40}|pull\/[1-9]\d*|compare\/[a-f0-9]{40}\.\.\.[a-f0-9]{40})$/;
const nonnegative=n=>Number.isSafeInteger(n)&&n>=0;
const ensure=(ok)=>{if(!ok)throw Error('リリース情報の形式・順序・参照先を確認してください。');};
ensure(semver.test(pkg.version)&&Array.isArray(records)&&records.length>0&&records[0].version===pkg.version);
const releases=records.map((r,i)=>{
    ensure(r && semver.test(r.version) && (i===0||newer(records[i-1].version,r.version)) && plain(r.title)&&plain(r.summary));
    ensure(r.date===undefined||validDate(r.date));
    ensure(r.period===undefined||plain(r.period));
    ensure(r.sections&&typeof r.sections==='object'&&!Array.isArray(r.sections)&&Object.keys(r.sections).length>0);
    ensure(Object.keys(r.sections).every(k=>Object.hasOwn(categories,k)));
    const sections=Object.entries(categories).filter(([k])=>Object.hasOwn(r.sections,k)).map(([k,label])=>{
        const items=r.sections[k];ensure(Array.isArray(items)&&items.length>0&&items.every(plain));return {label,items};
    });
    const statistics=r.statistics??[];
    ensure(Array.isArray(statistics)&&statistics.every(s=>s&&plain(s.label)&&[s.files,s.additions,s.deletions].every(nonnegative)));
    const links=r.links??[];
    ensure(Array.isArray(links)&&links.every(l=>l&&plain(l.label)&&typeof l.target==='string'&&validTarget.test(l.target)));
    return {version:r.version,date:r.date,period:r.period,title:r.title,summary:r.summary,sections,statistics,links:links.map(l=>({label:l.label,href:repository+l.target}))};
});
// The release date is recorded in the source data, never inferred from build time.
const info={version:pkg.version,builtAt:new Date().toISOString()};
const contents='/** Generated by npm run build:root; do not edit manually. */\n'+
  'import { installReleaseHistory } from "./release-history.js";\n'+
  'export const BUILD_INFO = '+JSON.stringify(info)+';\n'+
  'export const RELEASES = '+JSON.stringify(releases)+';\n'+
  'if (typeof document !== "undefined") {\n'+
  '  const stamp = new Intl.DateTimeFormat("ja-JP", {timeZone:"Asia/Tokyo",year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",hour12:false}).format(new Date(BUILD_INFO.builtAt));\n'+
  '  for (const el of document.querySelectorAll("[data-workbench-build-info]")) {\n'+
  '    const suffix = "  ·  build: " + stamp.split("/").join(".") + " JST";\n'+
  '    el.textContent = "WORKBENCH v" + BUILD_INFO.version + suffix;\n'+
  '    installReleaseHistory(el, BUILD_INFO.version, suffix, RELEASES);\n'+
  '  }\n'+
  '}\n';
const dest=path.join(root,'dist','workbench-build-info.js');
fs.mkdirSync(path.dirname(dest),{recursive:true});
fs.writeFileSync(dest,contents,'utf8');
const md=s=>s.replace(/[\\`*_{}\[\]()<>#!|]/g,'\\$&');
const changelog=['# WORKBENCH アップデート履歴','','<!-- release-notes.json から自動生成。手編集しないでください。 -->','','過去のリリース日は公開・リリースコミットの日付（日本時間）を記録しています。後続更新は同一バージョンにまとめています。日付・差分・リンクは確認できたもののみ掲載します。',''];
for(const [i,r] of releases.entries()){
    changelog.push(`## v${r.version}${i===0?'（最新版）':''}${r.date?' / '+r.date+' JST':''}`,'');
    if(r.period)changelog.push('開発・更新時期：'+md(r.period),'');
    changelog.push('**'+md(r.title)+'**','',md(r.summary),'');
    for(const s of r.sections)changelog.push('### '+s.label,'',...s.items.map(x=>'- '+md(x)),'');
    if(r.statistics.length)changelog.push('### 変更統計（生成物を含むGit差分）','',...r.statistics.map(s=>`- ${md(s.label)}：${s.files.toLocaleString('ja-JP')}ファイル、+${s.additions.toLocaleString('ja-JP')} / −${s.deletions.toLocaleString('ja-JP')} 行`),'');
    if(r.links.length)changelog.push('### 関連する変更','',...r.links.map(l=>`- [${md(l.label)}](${l.href})`),'');
}
const changelogPath=path.join(root,'CHANGELOG.md');
const markdown=changelog.join('\n');
if(!fs.existsSync(changelogPath)||fs.readFileSync(changelogPath,'utf8')!==markdown)fs.writeFileSync(changelogPath,markdown,'utf8');
console.log('[WORKBENCH] v'+info.version+' のビルド情報・リリース履歴を生成しました: '+info.builtAt);
