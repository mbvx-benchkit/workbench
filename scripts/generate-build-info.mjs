/** Build-time metadata for static GitHub Pages. No runtime network requests. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
if(!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(pkg.version))throw new Error('WORKBENCHのバージョン形式が不正です');
const info=Object.freeze({version:pkg.version,builtAt:new Date().toISOString()});
const contents='/** Generated by npm run build:root; do not edit manually. */\n'+
  'const BUILD_INFO = '+JSON.stringify(info)+';\n'+
  'const stamp = new Intl.DateTimeFormat("ja-JP", {timeZone:"Asia/Tokyo",year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",hour12:false}).format(new Date(BUILD_INFO.builtAt));\n'+
  'for (const el of document.querySelectorAll("[data-workbench-build-info]")) {\n'+
  '  el.textContent = "WORKBENCH v" + BUILD_INFO.version + "  ·  build: " + stamp.split("/").join(".") + " JST";\n'+
  '}\n';
const dest=path.join(root,'dist','workbench-build-info.js');
fs.mkdirSync(path.dirname(dest),{recursive:true});
fs.writeFileSync(dest,contents,'utf8');
console.log('[WORKBENCH] v'+info.version+' のビルド日時を更新しました: '+info.builtAt);
