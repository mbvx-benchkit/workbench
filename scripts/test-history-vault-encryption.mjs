/** PDF history is encrypted at rest, in backups and in recovery snapshots. */
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { jsPDF } from 'jspdf';
import { installFakeIndexedDB } from './test-support/fake-indexeddb.mjs';
installFakeIndexedDB();
const vault = await import('../shared/print-history-vault.js');
const {createBackupArchive,readBackupArchive}=await import('../dist/backup/backup-zip.js');
const {savePendingRecovery,readPendingRecovery,clearPendingRecovery}=await import('../dist/backup/restore-recovery.js');
const password='A long history password unique to these files 2026';
const pdf=new jsPDF();pdf.text('TESTHISTORYSECRET',20,30);
const blob=new Blob([pdf.output('arraybuffer')],{type:'application/pdf'});
// Seed a legacy v3 plain record. The first unlock must encrypt it without changing its ID.
await new Promise((resolve,reject)=>{
  const req=indexedDB.open('workbench-document-print-history',3);
  req.onupgradeneeded=()=>{
    const db=req.result,history=db.createObjectStore('history',{keyPath:'id'});
    history.put({id:'legacy-1',recipientName:'SECRET_RECIPIENT',fileName:'secret-history.pdf',createdAt:7,pdfBlob:blob});
    const meta=db.createObjectStore('history-meta',{keyPath:'id'});
    meta.createIndex('createdAtId',['createdAt','id'],{unique:true});
    meta.put({id:'legacy-1',recipientName:'SECRET_RECIPIENT',fileName:'secret-history.pdf',createdAt:7,pdfBytes:blob.size});
    const stats=db.createObjectStore('history-stats',{keyPath:'id'});
    stats.put({id:'total',count:1,totalBytes:blob.size});
  };
  req.onsuccess=()=>{req.result.close();resolve();};req.onerror=()=>reject(req.error);
});
await vault.createHistoryVault(password);
const rawDb=await new Promise((resolve,reject)=>{const req=indexedDB.open('workbench-document-print-history',4);req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);});
async function rawGet(store,id){const tx=rawDb.transaction(store,'readonly');return new Promise((resolve,reject)=>{const req=tx.objectStore(store).get(id);req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);});}
const encrypted=await rawGet('history','legacy-1');
const encryptedMeta=await rawGet('history-meta','legacy-1');
assert.equal(encrypted.pdfBlob,undefined);
assert.equal(encrypted.fileName,undefined);
assert.equal(encrypted.recipientName,undefined);
assert.equal(encryptedMeta.fileName,undefined);
assert.equal(encryptedMeta.recipientName,undefined);
assert.equal(encrypted.encryptedPdfBlob.size,blob.size+16);
assert.ok(!(await encrypted.encryptedPdfBlob.text()).includes('TESTHISTORYSECRET'));
const listing=await vault.getSealedHistoryPage();
assert.equal(listing.entries[0].fileName,'secret-history.pdf');
assert.equal((await vault.getSealedHistoryEntry('legacy-1')).pdfBlob.size,blob.size);
vault.lockHistoryVault();
await assert.rejects(vault.unlockHistoryVault('invalid history password'),/パスワード/);
await vault.unlockHistoryVault(password);
const {config,entries}=await vault.readOpaqueHistorySnapshot();
assert.equal(entries.length,1);
assert.ok(!JSON.stringify(entries).includes('SECRET_RECIPIENT'));
const snapshot={documentTemplates:[],redIndex:null,presetDocuments:[],printHistory:entries,historyVaultConfig:config};
await savePendingRecovery(snapshot);
const journal=await readPendingRecovery();
assert.ok(!JSON.stringify(journal.snapshot.printHistory).includes('SECRET_RECIPIENT'));
await clearPendingRecovery();
const archive=await createBackupArchive(snapshot);
const zip=await JSZip.loadAsync(new Uint8Array(await archive.arrayBuffer()));
const historyJson=await zip.file('document_builder/print-history/history.json').async('string');
assert.ok(!historyJson.includes('SECRET_RECIPIENT'));
assert.equal(JSON.parse(historyJson).version,2);
const binary=new Uint8Array(await zip.file('document_builder/print-history/encrypted/00001.bin').async('uint8array'));
assert.equal(binary.length,blob.size+16);
assert.notEqual(new TextDecoder('latin1').decode(binary.slice(0,8)),'%PDF-1.4');
const parsed=await readBackupArchive(new Uint8Array(await archive.arrayBuffer()));
assert.equal(parsed.sourceBackupVersion,3);
assert.equal(parsed.printHistory.length,1);
await vault.replaceOpaqueHistorySnapshot({config:parsed.historyVaultConfig,entries:parsed.printHistory});
await assert.rejects(vault.unlockHistoryVault('different password'),/パスワード/);
await vault.unlockHistoryVault(password);
assert.equal((await vault.getSealedHistoryEntry('legacy-1')).recipientName,'SECRET_RECIPIENT');
const plain={id:'old-v2',recipientName:'old',fileName:'old.pdf',createdAt:123,pdfBlob:blob};
const oldSealed=await vault.sealLegacyHistorySnapshot([plain]);
await vault.replaceOpaqueHistorySnapshot(oldSealed);
await vault.unlockHistoryVault(password);
assert.equal((await vault.getSealedHistoryEntry('old-v2')).fileName,'old.pdf');
rawDb.close();
console.log('PASS: legacy migration, encrypted metadata/PDF, wrong-password refusal, v3 backup and recovery roundtrip, v2 history re-sealing');
