/** Password rotation, orphan-staging recovery and irreversible reset. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { installFakeIndexedDB } from './test-support/fake-indexeddb.mjs';
installFakeIndexedDB();
const vault = await import('../shared/print-history-vault.js');
const oldPassword = 'Original PDF history password 2026!';
const newPassword = 'Updated PDF history password 2027!';
const pdf = new Blob(['%PDF-1.7\nThis document must remain protected\n%%EOF'],{type:'application/pdf'});
await vault.createHistoryVault(oldPassword);
await vault.addSealedHistory('Private Recipient', 'private.pdf',pdf);
const original=await vault.getSealedHistoryPage();
const id=original.entries[0].id;
assert.equal(original.entries[0].fileName,'private.pdf');
assert.equal((await vault.getSealedHistoryEntry(id)).pdfBlob.size,pdf.size);
await assert.rejects(vault.changeHistoryVaultPassword('wrong password',newPassword), /パスワード/);
assert.equal((await vault.getSealedHistoryEntry(id)).fileName,'private.pdf');
const db = await new Promise((resolve,reject)=>{
  const req=indexedDB.open('workbench-document-print-history',4);
  req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);
});
// Simulate an interrupted prior rotation. A retry must discard its ciphertext.
const leftover=db.transaction('history-vault','readwrite');
const leftoverDone=new Promise((resolve,reject)=>{leftover.oncomplete=resolve;leftover.onerror=()=>reject(leftover.error);});
leftover.objectStore('history-vault').put({id:'rotate:000000',entry:{id:'orphan'}});
await leftoverDone;
const count=await vault.changeHistoryVaultPassword(oldPassword,newPassword);
assert.equal(count,1);
vault.lockHistoryVault();
await assert.rejects(vault.unlockHistoryVault(oldPassword), /パスワード/);
await vault.unlockHistoryVault(newPassword);
const decrypted=await vault.getSealedHistoryEntry(id);
assert.equal(decrypted.recipientName,'Private Recipient');
assert.equal(await decrypted.pdfBlob.text(),await pdf.text());
const tx=db.transaction(['history-vault','history'],'readonly');
const oldKeys=await new Promise((resolve,reject)=>{const req=tx.objectStore('history-vault').getAll();req.onsuccess=()=>resolve(req.result.map(x=>x.id));req.onerror=()=>reject(req.error);});
assert.deepEqual(oldKeys,['vault'],'rotation temporary entries must be removed on success');
const encrypted=await new Promise((resolve,reject)=>{const req=tx.objectStore('history').get(id);req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);});
assert.equal(encrypted.pdfBlob,undefined);
assert.equal(encrypted.encryptedPdfBlob.type,'application/octet-stream');
assert.ok(!(await encrypted.encryptedPdfBlob.text()).includes('This document'));
await vault.resetHistoryVaultWithoutPassword();
assert.deepEqual(await vault.getSealedHistoryStats(),{count:0,totalBytes:0});
assert.equal((await vault.readOpaqueHistorySnapshot()).config,null);
assert.deepEqual((await vault.readOpaqueHistorySnapshot()).entries,[]);
await vault.createHistoryVault('Fresh history password after reset 2028');
assert.equal((await vault.getSealedHistoryPage()).entries.length,0);
db.close();
const html=readFileSync(new URL('../document_builder/index.html',import.meta.url),'utf8');
assert.match(html,/href="\.\/css\/history-vault\.css"/);
assert.match(html,/id="print-history-password-button"/);
const homeHtml=readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.match(homeHtml,/href="\.\/document_builder\/css\/history-vault\.css"/, 'backup page must style password prompts too');
const css=readFileSync(new URL('../document_builder/css/history-vault.css',import.meta.url),'utf8');
assert.match(css,/\.history-vault-dialog__input/);
assert.match(css,/\.history-vault-dialog__button--danger/);
const source=readFileSync(new URL('../shared/print-history-vault.js',import.meta.url),'utf8');
assert.ok(!source.includes('dialog.style.cssText'), 'password UI must use stylesheet classes');
console.log('PASS: password rotation remains encrypted, stale staging removed, forgotten-password reset, new vault, and CSS wiring');
